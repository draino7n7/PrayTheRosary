"""
PyMuPDF post-processing pipeline for the Pray The Rosary print PDF generator.

PDF Page Box & Compression Notes for Non-Python Developers:
-----------------------------------------------------------
In commercial print production (PDF/X workflows), a PDF page can define multiple
nested coordinate rectangles:
  - `MediaBox`: The full physical sheet or canvas size generated by ReportLab.
  - `BleedBox`: The rectangle to which background colors/artwork extend (typically
    `TrimBox` expanded outward by 0.125" = 9.0 pt on all four sides) to allow for
    slight mechanical variance during guillotine trimming.
  - `TrimBox`: The final finished dimensions of the page after the printer trims
    off the outer bleed margin (e.g., 6.0" x 9.0" = 432 x 648 pt, or 6.5" x 9.0"
    = 468 x 648 pt for Vervante covers and index tab sheets).

ReportLab natively sets only the `MediaBox`. After ReportLab finishes writing the
raw PDF, `postprocess_pdf()` opens the file with PyMuPDF (`pymupdf`) to:
  1. Inject explicit `TrimBox` and `BleedBox` metadata on every page when bleed,
     Vervante, or Office Depot mode is active.
  2. Run object garbage collection (`garbage=3`) to deduplicate shared font and
     XObject streams and apply lossless Flate compression (`deflate=True`), keeping
     each 50-page high-resolution PDF compact (~3.8 MB).
"""

from pathlib import Path

import pymupdf

from .config import (
    BLEED,
    PAGE_H,
    PAGE_W,
    VERVANTE_CROP_MARGIN,
    VERVANTE_TAB_EXT,
    is_vervante_wide_page,
    PrintConfig,
)


def postprocess_pdf(
    output_path: Path,
    cfg: PrintConfig,
    trans_x: float = 0.0,
    trans_y: float = 0.0,
) -> None:
    """
    Configures PDF `TrimBox` and `BleedBox` metadata per page according to `cfg`
    and optimizes/deflates internal PDF streams in-place.

    Args:
        output_path: Path to the newly generated ReportLab PDF file.
        cfg: Active `PrintConfig` profile.
        trans_x: Horizontal origin offset in points from `MediaBox` left edge to `TrimBox` left edge.
        trans_y: Vertical origin offset in points from `MediaBox` bottom/top edge to `TrimBox` edge.
    """
    doc = pymupdf.open(str(output_path))
    eff_w = cfg.effective_width

    if cfg.vervante:
        cx = VERVANTE_CROP_MARGIN
        cy = VERVANTE_CROP_MARGIN
        for idx, page in enumerate(doc):
            pnum = idx + 1
            pw = (PAGE_W + VERVANTE_TAB_EXT) if is_vervante_wide_page(pnum) else PAGE_W
            trim_rect = pymupdf.Rect(cx, cy, cx + pw, cy + PAGE_H)
            bleed_rect = pymupdf.Rect(cx - BLEED, cy - BLEED, cx + pw + BLEED, cy + PAGE_H + BLEED)
            page.set_trimbox(trim_rect)
            page.set_bleedbox(bleed_rect)
    elif cfg.bleed:
        trim_rect = pymupdf.Rect(BLEED, BLEED, BLEED + eff_w, BLEED + PAGE_H)
        bleed_rect = pymupdf.Rect(0, 0, eff_w + 2 * BLEED, PAGE_H + 2 * BLEED)
        for page in doc:
            page.set_trimbox(trim_rect)
            page.set_bleedbox(bleed_rect)
    elif cfg.office_depot:
        trim_rect = pymupdf.Rect(trans_x, trans_y, trans_x + eff_w, trans_y + PAGE_H)
        bleed_rect = pymupdf.Rect(
            trans_x - BLEED,
            trans_y - BLEED,
            trans_x + eff_w + BLEED,
            trans_y + PAGE_H + BLEED,
        )
        for page in doc:
            page.set_trimbox(trim_rect)
            page.set_bleedbox(bleed_rect)

    # Save optimized and deflated PDF via atomic temporary file replacement
    temp_path = output_path.with_suffix(".tmp.pdf")
    doc.save(str(temp_path), garbage=3, deflate=True)
    doc.close()
    temp_path.replace(output_path)
